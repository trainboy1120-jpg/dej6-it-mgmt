-- デバイステーブル
CREATE TABLE IF NOT EXISTS devices (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id TEXT NOT NULL UNIQUE,
  device_type TEXT NOT NULL,        -- SSP / FS / Avery / ZD611 / Handy / Radio / PC / Mobile
  model TEXT,
  asset_number TEXT,
  serial_number TEXT,
  status TEXT NOT NULL DEFAULT '正常', -- 正常 / 修理中 / Zebra登録済み / 発送済み / 修理完了
  ops_handler TEXT,
  it_handler TEXT,
  sim_url TEXT,
  memo TEXT,
  -- Zebra修理ポータル関連
  zebra_rma TEXT,
  defect_category TEXT,
  defect_detail TEXT,
  shipping_date DATE,
  tracking_number TEXT,
  return_date DATE,
  -- タイムスタンプ
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 修理履歴テーブル
CREATE TABLE IF NOT EXISTS repair_history (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id TEXT NOT NULL REFERENCES devices(device_id),
  from_status TEXT,
  to_status TEXT NOT NULL,
  handler TEXT,
  note TEXT,
  zebra_rma TEXT,
  tracking_number TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- updated_at 自動更新トリガー
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN NEW.updated_at = NOW(); RETURN NEW; END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_devices_updated_at ON devices;
CREATE TRIGGER trg_devices_updated_at
  BEFORE UPDATE ON devices
  FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- RLS（無効化：内部ツールのため）
ALTER TABLE devices DISABLE ROW LEVEL SECURITY;
ALTER TABLE repair_history DISABLE ROW LEVEL SECURITY;

-- インデックス
CREATE INDEX IF NOT EXISTS idx_devices_type ON devices(device_type);
CREATE INDEX IF NOT EXISTS idx_devices_status ON devices(status);
CREATE INDEX IF NOT EXISTS idx_repair_history_device ON repair_history(device_id);

